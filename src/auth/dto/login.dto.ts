import { ApiProperty } from '@nestjs/swagger';
import { IsString, Length, MinLength } from 'class-validator';

/**
 * Data Transfer Object representing the credentials required for user authentication.
 */
export class LoginDto {
    /**
     * User's unique login identifier (e.g., username, work email).
     */
    @ApiProperty({
        description: 'The unique login identifier for the user (username or email address).',
        example: 'john.doe@company.com',
        minLength: 3,
    })
    @IsString()
    @MinLength(3)
    loginIdentifier!: string;

    /**
     * 6-digit Time-based One-Time Password (TOTP) code for two-factor authentication.
     */
    @ApiProperty({
        description: 'The 6-digit TOTP verification code generated by an authenticator app.',
        example: '654321',
        minLength: 6,
        maxLength: 6,
    })
    @IsString()
    @Length(6, 6)
    totpCode!: string;
}